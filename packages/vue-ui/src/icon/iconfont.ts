/** 文档与业务侧遍历使用的图标列表，常用基础图标优先、业务图标后置。 */
export const iconfontNames: readonly IconfontName[] = [
  ...commonIconfontNames,
  ...iconfontSourceNames.filter((name) => !commonIconfontNameSet.has(name)),
];

const iconfontNameSet = new Set<string>(iconfontSourceNames);

/** 判断名称是否存在于随包发布的 Iconfont 集合中。 */
export function isIconfontName(name: string): name is IconfontName {
  return iconfontNameSet.has(name);
}
